"""Generates cl_shim.c: every OpenCL entry point in CL/cl.h forwarded to the device's own
libOpenCL.so, loaded lazily with dlopen. If the device has no OpenCL driver the shim reports
"no platform", so ggml's OpenCL backend finds nothing and llama.cpp stays on the CPU instead
of the app failing to load. Run: python3 gen_shim.py > cl_shim.c"""
import re, pathlib
src = pathlib.Path(__file__).with_name("CL").joinpath("cl.h").read_text()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
pat = re.compile(r"extern\s+CL_API_ENTRY\s+(.*?)\s+CL_API_CALL\s+(cl\w+)\s*\((.*?)\)\s*CL_API_SUFFIX[^;]*;", re.S)
funcs = []
for ret, name, params in pat.findall(src):
    ret = " ".join(ret.replace("CL_API_PREFIX__VERSION_1_1_DEPRECATED", "").replace("CL_API_PREFIX__VERSION_1_2_DEPRECATED","").replace("CL_API_PREFIX__VERSION_2_2_DEPRECATED","").split())
    params = " ".join(params.split())
    if params in ("void", ""):
        plist = []
    else:
        plist = [p.strip() for p in re.split(r",(?![^()]*\))", params)]
    names = []
    for p in plist:
        m = re.search(r"\(\s*CL_CALLBACK\s*\*\s*(\w+)\s*\)", p) or re.search(r"(\w+)\s*(\[\s*\])?$", p)
        names.append(m.group(1))
    funcs.append((ret, name, params if plist else "void", names))
out = ['/* Generated by gen_shim.py — do not edit. */',
 '#define CL_TARGET_OPENCL_VERSION 300', '#define CL_USE_DEPRECATED_OPENCL_1_0_APIS', '#define CL_USE_DEPRECATED_OPENCL_1_1_APIS',
 '#define CL_USE_DEPRECATED_OPENCL_1_2_APIS', '#define CL_USE_DEPRECATED_OPENCL_2_0_APIS', '#define CL_USE_DEPRECATED_OPENCL_2_1_APIS', '#define CL_USE_DEPRECATED_OPENCL_2_2_APIS',
 '#include <CL/cl.h>', '#include <dlfcn.h>', '#include <pthread.h>', '#include <stddef.h>', '#include <stdlib.h>', '',
 'static void *g_lib;', 'static pthread_once_t g_once = PTHREAD_ONCE_INIT;',
 'static void load_lib(void) {',
 '    /* 2.2.13: crash-safe mode (previous model load killed the process) sets IRIS_NO_OPENCL=1 before the',
 '     * first ggml call, so the OpenCL registry finds no platform and never touches the vendor driver. */',
 '    const char *off = getenv("IRIS_NO_OPENCL");',
 "    if (off && off[0] == '1') return;",
 '    static const char *paths[] = {"libOpenCL.so", "/vendor/lib64/libOpenCL.so", "/system/vendor/lib64/libOpenCL.so", "/system/lib64/libOpenCL.so", "libOpenCL_adreno.so"};',
 '    for (size_t i = 0; i < sizeof(paths) / sizeof(paths[0]) && !g_lib; i++) g_lib = dlopen(paths[i], RTLD_NOW | RTLD_LOCAL);',
 '}',
 'static void *sym(const char *name) { pthread_once(&g_once, load_lib); return g_lib ? dlsym(g_lib, name) : NULL; }',
 '/** 1 when the device driver was found (exported for diagnostics). */',
 '__attribute__((visibility("default"))) int iris_opencl_available(void) { pthread_once(&g_once, load_lib); return g_lib != NULL && dlsym(g_lib, "clGetPlatformIDs") != NULL; }', '']
for ret, name, params, names in funcs:
    args = ", ".join(names)
    errp = "errcode_ret" if "errcode_ret" in names else None
    out.append(f"{ret} CL_API_CALL {name}({params}) {{")
    out.append(f"    typedef {ret} (CL_API_CALL *fn_t)({params});")
    out.append(f'    static fn_t fn; if (!fn) fn = (fn_t) sym("{name}");')
    if ret == "void":
        out.append(f"    if (fn) fn({args});")
    else:
        out.append(f"    if (fn) return fn({args});")
        if name == "clGetPlatformIDs":
            out.append("    if (num_platforms) *num_platforms = 0;")
            out.append("    return -1001; /* CL_PLATFORM_NOT_FOUND_KHR */")
        elif ret == "cl_int":
            out.append("    return CL_INVALID_PLATFORM;")
        else:
            if errp: out.append(f"    if ({errp}) *{errp} = CL_INVALID_PLATFORM;")
            out.append(f"    return ({ret}) 0;")
    out.append("}")
print("\n".join(out))
