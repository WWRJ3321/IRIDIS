    /** 先按完整版本名（去掉 -full / -lite 等后缀）精确匹配，再退回到数字版本号匹配。 */
    fun find(version: String): Release? {
        val full = strip(version)
        return RELEASES.firstOrNull { it.version == full } ?: RELEASES.firstOrNull { it.version == base(version) }
    }

    /** "3.0.0 Beta6-full" → "3.0.0 Beta6"；"2.5.5-full" → "2.5.5"。 */
    fun strip(version: String): String = version.trim().replace(Regex("-(full|lite|debug)$"), "").trim()

    /** "2.5.5-full" / "2.5.5 beta" → "2.5.5"。 */
    fun base(version: String): String = Regex("^\\d+(\\.\\d+)+").find(version.trim())?.value ?: version.trim()

    /**
     * 升级后首次打开弹一次：欢迎页、新手引导都结束后，看过的版本 ≠ 当前版本且当前版本有内容。
     * 全新安装在引导结束时直接记为已看（见 MainActivity），不会紧接着再弹。
     */
    fun shouldShow(welcomeAccepted: Boolean, tourDone: Boolean, seen: String, current: String): Boolean =
        welcomeAccepted && tourDone && strip(seen) != strip(current) && find(current) != null
